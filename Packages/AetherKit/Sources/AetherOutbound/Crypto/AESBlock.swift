/// AES-128 单块加密（FIPS-197）：swift-crypto 不提供无模式的块加密，VMess 的 AuthID 需要（docs/06 §8.4）。
/// 只做加密方向、只处理 16 字节一块；查表实现不是常量时间，只用于 AuthID 这种不涉及长期机密比较的场合。
struct AES128Block {
    private let roundKeys: [UInt32]

    /// `key` 不是 16 字节时返回 nil。
    init?(key: [UInt8]) {
        guard key.count == 16 else { return nil }
        var words = [UInt32](repeating: 0, count: 44)
        for index in 0..<4 {
            words[index] =
                UInt32(key[4 * index]) << 24 | UInt32(key[4 * index + 1]) << 16 | UInt32(key[4 * index + 2]) << 8
                | UInt32(key[4 * index + 3])
        }
        var rcon: UInt32 = 0x0100_0000
        for index in 4..<44 {
            var temp = words[index - 1]
            if index % 4 == 0 {
                temp = Self.subWord((temp << 8) | (temp >> 24)) ^ rcon
                rcon = UInt32(Self.xtime(UInt8(rcon >> 24))) << 24
            }
            words[index] = words[index - 4] ^ temp
        }
        roundKeys = words
    }

    /// 加密一块；`block` 不是 16 字节时返回 nil。
    func encrypt(_ block: [UInt8]) -> [UInt8]? {
        guard block.count == 16 else { return nil }
        var state = block
        addRoundKey(&state, round: 0)
        for round in 1..<10 {
            subBytes(&state)
            shiftRows(&state)
            mixColumns(&state)
            addRoundKey(&state, round: round)
        }
        subBytes(&state)
        shiftRows(&state)
        addRoundKey(&state, round: 10)
        return state
    }

    private func addRoundKey(_ state: inout [UInt8], round: Int) {
        for column in 0..<4 {
            let word = roundKeys[round * 4 + column]
            state[4 * column] ^= UInt8(word >> 24)
            state[4 * column + 1] ^= UInt8(truncatingIfNeeded: word >> 16)
            state[4 * column + 2] ^= UInt8(truncatingIfNeeded: word >> 8)
            state[4 * column + 3] ^= UInt8(truncatingIfNeeded: word)
        }
    }

    private func subBytes(_ state: inout [UInt8]) {
        for index in 0..<16 {
            state[index] = Self.sbox[Int(state[index])]
        }
    }

    /// 状态按列存放：第 r 行第 c 列在 `state[4c + r]`。
    private func shiftRows(_ state: inout [UInt8]) {
        let copy = state
        for row in 1..<4 {
            for column in 0..<4 {
                state[4 * column + row] = copy[4 * ((column + row) % 4) + row]
            }
        }
    }

    private func mixColumns(_ state: inout [UInt8]) {
        for column in 0..<4 {
            let a0 = state[4 * column]
            let a1 = state[4 * column + 1]
            let a2 = state[4 * column + 2]
            let a3 = state[4 * column + 3]
            let all = a0 ^ a1 ^ a2 ^ a3
            state[4 * column] = a0 ^ all ^ Self.xtime(a0 ^ a1)
            state[4 * column + 1] = a1 ^ all ^ Self.xtime(a1 ^ a2)
            state[4 * column + 2] = a2 ^ all ^ Self.xtime(a2 ^ a3)
            state[4 * column + 3] = a3 ^ all ^ Self.xtime(a3 ^ a0)
        }
    }

    private static func xtime(_ value: UInt8) -> UInt8 {
        (value << 1) ^ (value & 0x80 != 0 ? 0x1B : 0)
    }

    private static func subWord(_ word: UInt32) -> UInt32 {
        UInt32(sbox[Int(word >> 24)]) << 24 | UInt32(sbox[Int((word >> 16) & 0xFF)]) << 16
            | UInt32(sbox[Int((word >> 8) & 0xFF)]) << 8 | UInt32(sbox[Int(word & 0xFF)])
    }

