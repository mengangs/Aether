#!/usr/bin/env bash
# 根据环境变量（CI 中来自 GitHub Actions 仓库变量）生成 Config/CI.xcconfig，覆盖 Identifiers.xcconfig 的默认值。
# 只写入非空的变量；全部为空时生成空文件，构建使用仓库中的通用默认值。见 docs/03 §3.1、§8.4。
set -euo pipefail
cd "$(dirname "$0")/.."

VARS=(
    AETHER_BUNDLE_ID_PREFIX
    AETHER_TUNNEL_BUNDLE_ID
    AETHER_WIDGET_BUNDLE_ID
    AETHER_APP_GROUP
    AETHER_KEYCHAIN_GROUP
    AETHER_TEAM_ID
    AETHER_URL_SCHEME
)

OUT="Config/CI.xcconfig"
{
    echo "// Generated by Scripts/write-ci-xcconfig.sh. Do not commit."
    for name in "${VARS[@]}"; do
        value="${!name:-}"
        if [[ -n "${value}" ]]; then
            # 只允许标识符中合法的字符，防止注入其它构建设置。
            if [[ ! "${value}" =~ ^[A-Za-z0-9.-]+$ ]]; then
                echo "error: ${name} contains invalid characters: ${value}" >&2
                exit 1
            fi
            echo "${name} = ${value}"
        fi
    done
} >"${OUT}"
echo "Wrote ${OUT}:"
cat "${OUT}"
